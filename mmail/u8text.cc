static int cp437Byte(unsigned long cp)
{
    if (cp < 0x80)
        return (int) cp;

    int lo = 0, hi = 127;

    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        unsigned long u = cp437_to_uni[cp437_by_uni[mid]];

        if (cp > u)
            lo = mid + 1;
        else if (cp < u)
            hi = mid - 1;
        else
            return cp437_by_uni[mid];
    }
    return -1;
}

// Shared by the two folds: tobyte() gives a character's byte in the target
// set, or -1 when it has none.
static char *u8fold(char *s, int (*tobyte)(unsigned long))
{
    char *in = s, *out = s;
    int len = strlen(s);

    while (*in) {
        unsigned long cp;
        int n = u8decode(in, len, &cp);

        in += n;
        len -= n;
        if (!u8cpWidth(cp))
            continue;

        int b = tobyte(cp);
        if (b < 0)
            switch (cp) {
            case 0x2010: case 0x2011: case 0x2012: case 0x2013: case 0x2014:
            case 0x2015: case 0x2212:
                b = '-';
                break;
            case 0x2018: case 0x2019: case 0x201A: case 0x2032:
                b = '\'';
                break;
            case 0x201C: case 0x201D: case 0x201E: case 0x2033:
                b = '"';
                break;
            case 0x2026:          // three bytes in, three out
                *out++ = '.';
                *out++ = '.';
                b = '.';
                break;
            default:
                b = '?';
            }
        *out++ = (char) b;
    }
    *out = '\0';
    return s;
}

char *u8toLatin1(char *s)
{
    return u8fold(s, latin1Byte);
}

char *u8toCP437(char *s)
{
    return u8fold(s, cp437Byte);
}

char *u8dupFold(const char *s, bool utf8, bool latin)
{
    if (!s)
        return 0;

    char *t = new char[strlen(s) + 1];

    strcpy(t, s);
    if (utf8)
        latin ? u8toLatin1(t) : u8toCP437(t);
    return t;
}

char *u8dupEncode(const char *s, bool latin)
{
    if (!s)
        return 0;

    char *t = new char[strlen(s) * 3 + 1], *p = t;

    for (; *s; s++) {
        unsigned char b = (unsigned char) *s;
        unsigned long cp = (latin || (b < 0x80)) ? b : cp437_to_uni[b];

        if (cp < 0x80)
            *p++ = (char) cp;
        else {
            if (cp < 0x800)
                *p++ = (char) (0xC0 | (cp >> 6));
            else {
                *p++ = (char) (0xE0 | (cp >> 12));
                *p++ = (char) (0x80 | ((cp >> 6) & 0x3F));
            }
            *p++ = (char) (0x80 | (cp & 0x3F));
        }
    }
    *p = '\0';
    return t;
}

int u8fit(const char *s, int len, int maxcols, int maxbytes, bool utf8)
{
    int cols = 0, pos = 0;

    len = textLen(s, len);
    int cap = (maxbytes >= 0 && maxbytes < len) ? maxbytes : len;

    if (!utf8)
        return (maxcols >= 0 && maxcols < cap) ? maxcols : cap;

    // decode against the whole text, so a character cut by the byte budget
    // is left out rather than read as a broken sequence
    while (pos < cap) {
        int w, n = u8char(s + pos, len - pos, &w);

        if (pos + n > cap || (maxcols >= 0 && cols + w > maxcols))
            break;
        cols += w;
        pos += n;
    }
    return pos;
}
